s32 utils_name_compare(const char *a, const char *b, s32 keep_case, u32 max_len)
{
    bool map = g_language_index != 10;
    u32 i = 0;

    if (!a) return b ? -1 : 0;
    if (!b) return 1;
    if (a[0] != '\0') {
        while (b[i] != '\0') {
            u8 x = (u8)a[i], y = (u8)b[i];

            if (map) {
                x = g_name_map[x][0];
                y = g_name_map[y][0];
            }
            if (!keep_case) {
                x = g_name_map[x][2];
                y = g_name_map[y][2];
            }
            if (x != y) return x < y ? -1 : 1;
            if (max_len > 0 && i == max_len - 1) return 0;
            i++;
            if (a[i] == '\0') break;
        }
    }
    if (a[i] != '\0') return 1;
    if (b[i] != '\0') return -1;
    return 0;
}
